      if (ci < 0) begin $display("P2A_FAIL unknown raw tag"); errors = errors + 1; end
      else for (k=0;k<4;k=k+1) begin
        if ($signed(dut.tree5_r[k]) !== exp_raw[ci][g*4+k]) begin $display("P2A_FAIL raw id=%0d group=%0d lane=%0d got=%0d exp=%0d", dut.id_pipe[7],g,k,$signed(dut.tree5_r[k]),exp_raw[ci][g*4+k]); errors=errors+1; end
        raw_checks = raw_checks + 1;
      end
    end
    if (dut.valid_pipe[8]) begin
      integer ci, g, k;
      ci = case_index(dut.id_pipe[8]); g = dut.group_pipe[8];
      if (ci >= 0) for (k=0;k<4;k=k+1) begin
        if ($signed(dut.biased_r[k]) !== exp_biased[ci][g*4+k]) begin $display("P2A_FAIL biased id=%0d group=%0d lane=%0d",dut.id_pipe[7],g,k); errors=errors+1; end
        biased_checks = biased_checks + 1;
      end
    end
    if (dut.valid_pipe[9]) begin
      integer ci, g, k;
      ci = case_index(dut.id_pipe[9]); g = dut.group_pipe[9];
      if (ci >= 0) for (k=0;k<4;k=k+1) begin
        if ($signed(dut.shifted_r[k]) !== exp_shifted[ci][g*4+k]) begin $display("P2A_FAIL shifted id=%0d group=%0d lane=%0d",dut.id_pipe[9],g,k); errors=errors+1; end
        shifted_checks = shifted_checks + 1;
      end
    end
    if (dut.stage_valid) begin
      integer ci, g, k;
      ci = case_index(dut.stage_id); g = dut.stage_group;
      if (ci >= 0 && g == 0 && first_stage_cycle[ci] < 0) first_stage_cycle[ci] = cycle;
      if (ci >= 0) for (k=0;k<4;k=k+1) begin
        if ($signed(dut.stage16_r[k]) !== exp_stage16[ci][g*4+k]) begin $display("P2A_FAIL stage16 id=%0d group=%0d lane=%0d",dut.stage_id,g,k); errors=errors+1; end
        stage16_checks = stage16_checks + 1;
      end
    end
    if (dut.issue_pulse) begin
      integer ci, g;
      ci = case_index(dut.issue_vector_id); g = dut.issue_group;
      if (ci >= 0) begin
        if (issue_count[ci] == 0) first_issue_cycle[ci] = cycle;
        if (g !== issue_count[ci]) begin $display("P2A_FAIL issue group id=%0d got=%0d exp=%0d",dut.issue_vector_id,g,issue_count[ci]); errors=errors+1; end
        if (issue_count[ci] != 0 && cycle != last_issue_cycle[ci]+1) begin $display("P2A_FAIL issue bubble id=%0d group=%0d",dut.issue_vector_id,g); errors=errors+1; end
        issue_count[ci] = issue_count[ci] + 1; last_issue_cycle[ci] = cycle;
      end
    end
    if (dut.launch_pulse) begin
      if (phase == 1 && launch_count != 0 && cycle-last_launch_cycle != 16) begin $display("P2A_FAIL vector interval=%0d",cycle-last_launch_cycle); errors=errors+1; end
      $display("P2A_LAUNCH phase=%0d id=%0d cycle=%0d",phase,dut.issue_vector_id,cycle);
      launch_count = launch_count + 1; last_launch_cycle = cycle;
    end
    if (result_valid && result_ready) begin
      integer ci, g, k;
      ci = case_index(result_vector_id); g = result_group;
      if (ci < 0) begin $display("P2A_FAIL unknown output tag"); errors=errors+1; end
      else begin
        if (g == 0 && first_out_cycle[ci] < 0) first_out_cycle[ci] = cycle;
        if (g !== out_next_group[ci]) begin $display("P2A_FAIL output group id=%0d got=%0d exp=%0d",result_vector_id,g,out_next_group[ci]); errors=errors+1; end
        if (phase == 1 && out_next_group[ci] != 0 && cycle != last_out_cycle[ci]+1) begin $display("P2A_FAIL output bubble id=%0d group=%0d",result_vector_id,g); errors=errors+1; end
        for (k=0;k<4;k=k+1) if ($signed(result_data[k*16 +: 16]) !== exp_stage16[ci][g*4+k]) begin $display("P2A_FAIL output data id=%0d group=%0d lane=%0d got=%0d exp=%0d",result_vector_id,g,k,$signed(result_data[k*16 +: 16]),exp_stage16[ci][g*4+k]); errors=errors+1; end
        if ((g == 0) != result_first || (g == 15) != result_last) begin $display("P2A_FAIL first/last tag id=%0d group=%0d",result_vector_id,g); errors=errors+1; end
        out_next_group[ci] = out_next_group[ci] + 1; last_out_cycle[ci] = cycle; out_count = out_count + 1; output_checks = output_checks + 4;
      end
    end
  end

  always @(negedge clk) begin
    if ((fifo_occupied + reserved_count) > 32 || reserved_count > 32) begin $display("P2A_FAIL capacity occupied=%0d reserved=%0d",fifo_occupied,reserved_count); errors=errors+1; end
  end

  task automatic send_vector(input integer ci);
    integer g, k;
    begin
      while (!vector_start_ready) @(negedge clk);
      vector_start_id = ids[ci]; load_data = '0;
      for (k=0;k<4;k=k+1) load_data[k*16 +: 16] = in_vec[ci][k];
      vector_start = 1'b1; load_valid = 1'b1; @(negedge clk); vector_start = 1'b0; load_valid = 1'b0;
      for (g=1; g<16; g=g+1) begin
        while (!load_ready) @(negedge clk);
        load_data = '0;
        for (k=0;k<4;k=k+1) load_data[k*16 +: 16] = in_vec[ci][g*4+k];
        load_valid = 1'b1; @(negedge clk); load_valid = 1'b0;
      end
    end
  endtask

  task automatic reset_monitors;
    integer q;
    begin
      launch_count = 0; last_launch_cycle = -1; out_count = 0;
      raw_checks=0; biased_checks=0; shifted_checks=0; stage16_checks=0; output_checks=0;
      for (q=0;q<NUM_CASES;q=q+1) begin issue_count[q]=0; last_issue_cycle[q]=-1; first_issue_cycle[q]=-1; first_stage_cycle[q]=-1; first_out_cycle[q]=-1; out_next_group[q]=0; last_out_cycle[q]=-1; end
    end
  endtask

  initial begin
    reset_monitors();
    repeat (5) @(negedge clk); rst_n = 1'b1;
    phase = 1; result_ready = 1'b1;
    send_vector(0); send_vector(1); send_vector(2);
    begin integer guard; guard=0; while (out_count < 48) begin @(negedge clk); guard=guard+1; if (guard>2000) begin $display("P2A_FAIL timeout phase1"); errors=errors+1; disable fork; end end end
    if (issue_count[0] != 16 || issue_count[1] != 16 || issue_count[2] != 16) begin $display("P2A_FAIL phase1 issue counts"); errors=errors+1; end
    if (launch_count != 3) begin $display("P2A_FAIL phase1 launch_count=%0d",launch_count); errors=errors+1; end
    if (raw_checks != 192 || biased_checks != 192 || shifted_checks != 192 || stage16_checks != 192 || output_checks != 192) begin $display("P2A_FAIL phase1 stage counts raw=%0d biased=%0d shifted=%0d stage16=%0d output=%0d",raw_checks,biased_checks,shifted_checks,stage16_checks,output_checks); errors=errors+1; end
    rst_n = 1'b0; repeat (4) @(negedge clk); reset_monitors(); rst_n = 1'b1;
    phase = 2; result_ready = 1'b0;
    send_vector(3); send_vector(4);
    repeat (350) @(negedge clk);
    if (launch_count != 2) begin $display("P2A_FAIL backpressure launch_count=%0d (expected 2)",launch_count); errors=errors+1; end
    if ((fifo_occupied + reserved_count) > 32) begin $display("P2A_FAIL backpressure capacity"); errors=errors+1; end
    result_ready = 1'b1;
    begin integer guard; guard=0; while (out_count < 32) begin @(negedge clk); guard=guard+1; if (guard>1000) begin $display("P2A_FAIL timeout phase2"); errors=errors+1; break; end end end
    if (issue_count[3] != 16 || issue_count[4] != 16) begin $display("P2A_FAIL phase2 issue counts"); errors=errors+1; end
    $display("P2A_METRIC phase1_launch_interval_expected=16 issue_group_interval=1");
    $display("P2A_METRIC phase2_launch_count=%0d fifo_occupied=%0d reserved=%0d",launch_count,fifo_occupied,reserved_count);
    for (i=0;i<NUM_CASES;i=i+1) if (issue_count[i] != 0) $display("P2A_LATENCY id=%0d issue0=%0d stage_write0=%0d output0=%0d stage_latency=%0d output_latency=%0d",ids[i],first_issue_cycle[i],first_stage_cycle[i],first_out_cycle[i],first_stage_cycle[i]-first_issue_cycle[i],first_out_cycle[i]-first_issue_cycle[i]);
    if (errors == 0 && raw_checks == 128 && biased_checks == 128 && shifted_checks == 128 && stage16_checks == 128 && output_checks == 128) begin
      $display("P2A_TB_PASS raw=%0d biased=%0d shifted=%0d stage16=%0d output=%0d launches=%0d",raw_checks,biased_checks,shifted_checks,stage16_checks,output_checks,launch_count);
    end else begin $display("P2A_TB_FAIL errors=%0d raw=%0d biased=%0d shifted=%0d stage16=%0d output=%0d launches=%0d",errors,raw_checks,biased_checks,shifted_checks,stage16_checks,output_checks,launch_count); end
    if (errors != 0 || raw_checks != 128 || biased_checks != 128 || shifted_checks != 128 || stage16_checks != 128 || output_checks != 128) $fatal(1, "P2A functional check failed");
    $finish;
  end
endmodule
